from pyspark.sql import SparkSession
from pyspark.sql.functions import col, when, length, isnan, isnull

spark = SparkSession.builder.appName("filter").master("local[*]").getOrCreate()

# 准备数据
data = [
    (1, "张三", 25, "北京", "13800138001"),
    (2, "", None, "上海", "12345"),           # 空字符串、空值、无效手机号
    (3, None, 30, "", "13800138002"),
    (4, "李四", -5, "广州", "13800138003"),    # 负数年龄
    (5, "王五", 150, "深圳", "abc"),           # 年龄过大、手机号非数字
    (6, "赵", 28, "北京", "13800138004")       # 姓名太短
]
df = spark.createDataFrame(data, ["id", "name", "age", "city", "phone"])
df.show()
# +---+----+----+----+-----------+
# | id|name| age|city|      phone|
# +---+----+----+----+-----------+
# |  1|张三|  25|北京|13800138001|
# |  2|    |null|上海|      12345|
# |  3|null|  30|    |13800138002|
# |  4|李四|  -5|广州|13800138003|
# |  5|王五| 150|深圳|        abc|
# |  6| 赵|  28|北京|13800138004|
# +---+----+----+----+-----------+

# ============ filter() / where()：条件过滤 ============
# 过滤年龄在 0-120 之间的有效数据
df.filter((col("age") > 0) & (col("age") <= 120)).show()
# +---+----+---+----+-----------+
# | id|name|age|city|      phone|
# +---+----+---+----+-----------+
# |  1|张三| 25|北京|13800138001|
# |  3|null| 30|    |13800138002|
# |  6| 赵| 28|北京|13800138004|
# +---+----+---+----+-----------+

# 过滤姓名非空且长度 >= 2
df.filter(col("name").isNotNull() & (length(col("name")) >= 2)).show()
# +---+----+---+----+-----------+
# | id|name|age|city|      phone|
# +---+----+---+----+-----------+
# |  1|张三| 25|北京|13800138001|
# |  4|李四| -5|广州|13800138003|
# |  5|王五|150|深圳|        abc|
# +---+----+---+----+-----------+

# 过滤手机号（11位数字）
df.filter(col("phone").rlike("^\\d{11}$")).show()
# +---+----+---+----+-----------+
# | id|name|age|city|      phone|
# +---+----+---+----+-----------+
# |  1|张三| 25|北京|13800138001|
# |  3|null| 30|    |13800138002|
# |  4|李四| -5|广州|13800138003|
# |  6| 赵| 28|北京|13800138004|
# +---+----+---+----+-----------+

# 组合条件：年龄有效 AND 姓名非空 AND 手机号有效
df.filter(
    (col("age") > 0) &
    (col("age") <= 120) &
    col("name").isNotNull() &
    (length(col("name")) >= 2) &
    col("phone").rlike("^\\d{11}$")
).show()
# +---+----+---+----+-----------+
# | id|name|age|city|      phone|
# +---+----+---+----+-----------+
# |  1|张三| 25|北京|13800138001|
# +---+----+---+----+-----------+

# ============ 使用 SQL 表达式过滤 ============
df.where("age > 0 AND age <= 120 AND name IS NOT NULL AND LENGTH(name) >= 2").show()

# ============ 过滤空值和空字符串 ============
# 过滤 name 为空或空字符串的行
df.filter((col("name").isNull()) | (col("name") == "")).show()
# +---+----+----+----+-----------+
# | id|name| age|city|      phone|
# +---+----+----+----+-----------+
# |  2|    |null|上海|      12345|
# |  3|null|  30|    |13800138002|
# +---+----+----+----+-----------+

spark.stop()