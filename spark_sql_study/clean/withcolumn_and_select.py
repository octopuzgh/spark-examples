from pyspark.sql import SparkSession
from pyspark.sql.functions import col, lit, when, concat, expr

spark = SparkSession.builder.appName("column").master("local[*]").getOrCreate()

# 准备数据
data = [(1, "张三", 25, 15000), (2, "李四", 30, 18000), (3, "王五", 28, 12000)]
df = spark.createDataFrame(data, ["id", "name", "age", "salary"])
df.show()
# +---+----+---+------+
# | id|name|age|salary|
# +---+----+---+------+
# |  1|张三| 25| 15000|
# |  2|李四| 30| 18000|
# |  3|王五| 28| 12000|
# +---+----+---+------+

# ============ withColumn()：添加或替换列 ============
# 添加新列
df.withColumn("age_plus_1", col("age") + 1).show()
# +---+----+---+------+----------+
# | id|name|age|salary|age_plus_1|
# +---+----+---+------+----------+
# |  1|张三| 25| 15000|        26|
# |  2|李四| 30| 18000|        31|
# |  3|王五| 28| 12000|        29|
# +---+----+---+------+----------+

# 添加常量列
df.withColumn("country", lit("中国")).show()
# +---+----+---+------+-------+
# | id|name|age|salary|country|
# +---+----+---+------+-------+
# |  1|张三| 25| 15000|   中国|
# |  2|李四| 30| 18000|   中国|
# |  3|王五| 28| 12000|   中国|
# +---+----+---+------+-------+

# 条件列（类似 if-else）
df.withColumn("level", when(col("salary") >= 15000, "高级")
                     .otherwise("初级")).show()
# +---+----+---+------+-----+
# | id|name|age|salary|level|
# +---+----+---+------+-----+
# |  1|张三| 25| 15000| 高级|
# |  2|李四| 30| 18000| 高级|
# |  3|王五| 28| 12000| 初级|
# +---+----+---+------+-----+

# 组合列
df.withColumn("description", concat(col("name"), lit("，年龄"), col("age"), lit("岁"))).show()
# +---+----+---+------+-------------------+
# | id|name|age|salary|        description|
# +---+----+---+------+-------------------+
# |  1|张三| 25| 15000|张三，年龄25岁|
# |  2|李四| 30| 18000|李四，年龄30岁|
# |  3|王五| 28| 12000|王五，年龄28岁|
# +---+----+---+------+-------------------+

# 计算列
df.withColumn("annual_salary", col("salary") * 12).show()
# +---+----+---+------+-------------+
# | id|name|age|salary|annual_salary|
# +---+----+---+------+-------------+
# |  1|张三| 25| 15000|       180000|
# |  2|李四| 30| 18000|       216000|
# |  3|王五| 28| 12000|       144000|
# +---+----+---+------+-------------+

# 替换列（同名会覆盖）
df.withColumn("salary", col("salary") / 1000).show()
# +---+----+---+------+
# | id|name|age|salary|
# +---+----+---+------+
# |  1|张三| 25|  15.0|
# |  2|李四| 30|  18.0|
# |  3|王五| 28|  12.0|
# +---+----+---+------+

# ============ select()：选择特定列 ============
# 选择部分列
df.select("name", "age").show()
# +----+---+
# |name|age|
# +----+---+
# |张三| 25|
# |李四| 30|
# |王五| 28|
# +----+---+

# 选择并计算
df.select(col("name"), (col("salary") / 1000).alias("salary_k")).show()
# +----+---------+
# |name|salary_k|
# +----+---------+
# |张三|     15.0|
# |李四|     18.0|
# |王五|     12.0|
# +----+---------+

# 使用表达式
df.select(expr("name"), (expr("age")*12).alias("age_in_months")).show()
# +----+-------------+
# |name|age_in_months|
# +----+-------------+
# |张三|          300|
# |李四|          360|
# |王五|          336|
# +----+-------------+

# 删除列（select 不选即可）
df.select([c for c in df.columns if c != "salary"]).show()
# +---+----+---+
# | id|name|age|
# +---+----+---+
# |  1|张三| 25|
# |  2|李四| 30|
# |  3|王五| 28|
# +---+----+---+

spark.stop()